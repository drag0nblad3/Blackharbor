#!/usr/bin/env node
// Build the multi-file publish of nightwatch.html (see README "Publishing").
//   node tools/split.js [outDir]        default outDir: ../dist
// nightwatch.html stays the one source file. This writes:
//   index.html  tiny page: head, #app, script/link tags, boot script
//   game.css    first <style> (layout, UI)
//   data.js     plain data tables lifted out of the game script (DATA below)
//   game.js     the rest of the game script (rules, views)
//   art.css     art-block <style>
//   sprite.js   the #nwsprite SVG, written into the page where it stood
//   art.js      art-block drawing script
const fs = require('fs'), path = require('path'), vm = require('vm');
const SRC = path.join(__dirname, '..', 'nightwatch.html');
const OUT = path.resolve(process.argv[2] || path.join(__dirname, '..', 'dist'));
// Tables with no code in them. A table that turns out to reference anything is left in game.js.
const DATA = ['HERO_BASE', 'POWERS', 'GEAR', 'SETS', 'VILLAINS', 'VINTEL', 'VLINES', 'VSFX', 'ALL_ITEMS',
  'START_UNLOCK', 'ARC_UNLOCK', 'MID_UNLOCK', 'DEFEAT_UNLOCK', 'FAC', 'ORIGIN', 'GLOSS'];

// The art-block marker comment mentions <script>, so drop it before matching tags.
const html = fs.readFileSync(SRC, 'utf8').replace(/<!-- ===== NW-ART-BLOCK[\s\S]*?-->\n?/, '');

// End of a JS literal starting at s[i] ('{' or '['), skipping strings and comments.
function litEnd(s, i) {
  let d = 0;
  for (; i < s.length; i++) {
    const c = s[i];
    if (c === '"' || c === "'" || c === '`') {
      const q = c;
      for (i++; i < s.length && s[i] !== q; i++) if (s[i] === '\\') i++;
      if (q === '`') return -1; // templates may hold code: not plain data
    } else if (c === '/' && s[i + 1] === '/') { i = s.indexOf('\n', i); if (i < 0) return -1; }
    else if (c === '/' && s[i + 1] === '*') { i = s.indexOf('*/', i) + 1; if (i <= 0) return -1; }
    else if (c === '{' || c === '[') d++;
    else if (c === '}' || c === ']') { d--; if (!d) return i + 1; }
  }
  return -1;
}

function liftData(js) {
  const out = [], skipped = [];
  for (const name of DATA) {
    const m = new RegExp('^const\\s+' + name + '\\s*=\\s*(?=[\\[{])', 'm').exec(js);
    if (!m) { skipped.push(name + ' (not found)'); continue; }
    const end = litEnd(js, m.index + m[0].length);
    if (end < 0) { skipped.push(name + ' (not a plain literal)'); continue; }
    let stop = end; while (js[stop] === ' ') stop++; if (js[stop] === ';') stop++;
    const decl = js.slice(m.index, stop);
    try { vm.runInNewContext(decl.replace(/^const/, 'var'), Object.create(null)); }
    catch (e) { skipped.push(name + ' (' + e.message.slice(0, 60) + ')'); continue; }
    out.push(decl.replace(/;?$/, ';'));
    js = js.slice(0, m.index) + js.slice(stop);
  }
  return { data: out.join('\n'), js, skipped };
}

// Pull out <style>, <script> and the sprite in document order.
const parts = [];
const re = /<style>([\s\S]*?)<\/style>|<script>([\s\S]*?)<\/script>|(<svg id="nwsprite"[\s\S]*?<\/svg>)/g;
let page = '', last = 0, m;
const files = {}, cssN = ['game.css', 'art.css'], jsN = ['game.js', 'art.js'];
let ci = 0, si = 0;
while ((m = re.exec(html))) {
  page += html.slice(last, m.index); last = re.lastIndex;
  if (m[1] != null) { const f = cssN[ci++]; files[f] = m[1]; page += `<link rel="stylesheet" href="${f}">`; }
  else if (m[3] != null) { files['sprite.js'] = 'document.currentScript.insertAdjacentHTML("beforebegin",' + JSON.stringify(m[3]) + ');\n'; page += '<script src="sprite.js"></script>'; }
  else if (si < jsN.length) {
    const f = jsN[si++];
    if (f === 'game.js') {
      const r = liftData(m[2]);
      if (r.skipped.length) console.log('left in game.js:', r.skipped.join(', '));
      files['data.js'] = '// Nightwatch Arc data tables. Generated by tools/split.js from nightwatch.html: edit that file, not this one.\n' + r.data + '\n';
      files[f] = r.js;
      page += '<script src="data.js"></script>\n<script src="game.js"></script>';
    } else { files[f] = m[2]; page += `<script src="${f}"></script>`; }
  } else page += m[0]; // boot script stays inline
}
page += html.slice(last);
if (ci !== 2 || si !== 2 || !files['sprite.js']) throw new Error(`unexpected layout: ${ci} styles, ${si} scripts, sprite ${!!files['sprite.js']}`);
// Scripts take the page's encoding; index.html has no non-ASCII text left to sniff, so say UTF-8.
files['index.html'] = '<meta charset="utf-8">\n' + page;

fs.mkdirSync(OUT, { recursive: true });
for (const [f, t] of Object.entries(files)) fs.writeFileSync(path.join(OUT, f), t);
for (const f of Object.keys(files)) console.log(String(Buffer.byteLength(files[f])).padStart(8), f);
console.log('wrote', OUT);
